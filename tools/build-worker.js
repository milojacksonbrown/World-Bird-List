// Builds worker/dist/lyrebird.js: Lyrebird for Cloudflare Workers.
//
// It's the shared code from the Apps Script files (NameFixesAssistant.gs, AskYourList.gs and
// Lyrebird/Lyrebird.gs), unchanged, followed by worker/main.js, which does the Worker's sending
// and storing. So the Worker and Apps Script Lyrebird check requests, build prompts, check the
// AI's answers and apply the caps with exactly the same code.
//
// Run from the repo folder after changing any of those files, then deploy (worker/README.md):
//   node tools/build-worker.js
// A test (Tests/worker.test.js) fails if the bundle is out of date.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const SHARED = ['NameFixesAssistant.gs', 'AskYourList.gs', 'Lyrebird/Lyrebird.gs'];
const OUT = path.join(root, 'worker', 'dist', 'lyrebird.js');

function bundle() {
  return '// GENERATED by tools/build-worker.js. Do not edit here: edit the files named below and re-run.\n' +
    SHARED.concat('worker/main.js').map(f => '\n// ===== ' + f + ' =====\n' + fs.readFileSync(path.join(root, f), 'utf8')).join('');
}

module.exports = { bundle, OUT };
if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, bundle());
  console.log('Wrote ' + path.relative(root, OUT) + ' (' + Math.round(fs.statSync(OUT).size / 1024) + ' KB)');
}
